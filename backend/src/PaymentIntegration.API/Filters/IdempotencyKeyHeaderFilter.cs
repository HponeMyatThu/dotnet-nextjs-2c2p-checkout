using Microsoft.OpenApi;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace PaymentIntegration.API.Filters;

public class IdempotencyKeyHeaderFilter : IOperationFilter
{
    public void Apply(OpenApiOperation operation, OperationFilterContext context)
    {
        var httpMethod = context.ApiDescription.HttpMethod;
        var relativePath = context.ApiDescription.RelativePath?.TrimStart('/');

        // Add Idempotency-Key header documentation on POST /api/checkout
        if (string.Equals(httpMethod, "POST", StringComparison.OrdinalIgnoreCase) &&
            relativePath != null && relativePath.StartsWith("api/checkout", StringComparison.OrdinalIgnoreCase))
        {
            operation.Parameters ??= new List<IOpenApiParameter>();
            operation.Parameters.Add(new OpenApiParameter
            {
                Name = "Idempotency-Key",
                In = ParameterLocation.Header,
                Required = true,
                Description = "Unique UUID idempotency token generated by the client to prevent duplicate charges (e.g. on double clicks, retries).",
                Schema = new OpenApiSchema
                {
                    Type = JsonSchemaType.String,
                    Format = "uuid"
                }
            });
        }
    }
}
